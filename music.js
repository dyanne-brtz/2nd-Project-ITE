const lyricsTitle = document.getElementById("lyrics-title");
const lyricsArtist = document.getElementById("lyrics-artist");
const lyricsText = document.getElementById("lyrics-text");
const audioPlayer = document.getElementById("audio-player");
const playBtn = document.getElementById("play-btn");

const urlParams = new URLSearchParams(window.location.search);
const songId = urlParams.get('song');
const song = songs[songId];

if (song) {
    lyricsTitle.textContent = song.title;
    lyricsArtist.textContent = song.artist;
    audioPlayer.src = song.audio;

    song.lyrics.forEach((line) => {
        const p = document.createElement("p");
        p.textContent = line.text;
        p.className = "lyric-line";
        p.dataset.time = line.time;
        lyricsText.appendChild(p);
    });
} else {
    lyricsTitle.textContent = "Song Not Found";
    lyricsArtist.textContent = "Please go back and select a song.";
}

audioPlayer.addEventListener("timeupdate", () => {
    const lines = document.querySelectorAll(".lyric-line");
    if (lines.length === 0) return;

    const currentTime = audioPlayer.currentTime;
    lines.forEach((line) => {
        const lineTime = parseFloat(line.dataset.time);
        if (currentTime >= lineTime) {
            if (!line.classList.contains("active")) {
                lines.forEach(l => l.classList.remove("active"));
                line.classList.add("active");
                line.scrollIntoView({ behavior: "smooth", block: "center" });
            }
        }
    });
});

if (playBtn) {
    playBtn.addEventListener("click", () => {
        if (audioPlayer.paused) {
            audioPlayer.play().catch(error => console.log(error));
            playBtn.textContent = "⏸";
        } else {
            audioPlayer.pause();
            playBtn.textContent = "▶";
        }
    });
}

    